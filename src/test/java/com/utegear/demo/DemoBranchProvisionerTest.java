package com.utegear.demo;

import static org.assertj.core.api.Assertions.*;

import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import org.springframework.transaction.support.TransactionTemplate;

class DemoBranchProvisionerTest {
    JdbcTemplate jdbc;
    TransactionTemplate transaction;
    DemoBranchProvisioner provisioner;
    BCryptPasswordEncoder passwords = new BCryptPasswordEncoder(4);

    @BeforeEach
    void setup() {
        var source = new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(source);
        transaction = new TransactionTemplate(new DataSourceTransactionManager(source));
        jdbc.execute("CREATE TABLE stores(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar, address varchar, province varchar, district varchar, email varchar, opening_time time, closing_time time, description varchar, active boolean, created_at timestamp, updated_at timestamp)");
        jdbc.execute("CREATE TABLE roles(id bigint PRIMARY KEY, name varchar)");
        jdbc.execute("CREATE TABLE users(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, full_name varchar, email varchar UNIQUE, password_hash varchar, enabled boolean, assigned_store_id bigint REFERENCES stores(id), created_at timestamp, updated_at timestamp)");
        jdbc.execute("CREATE TABLE user_roles(user_id bigint REFERENCES users(id), role_id bigint REFERENCES roles(id), PRIMARY KEY(user_id,role_id))");
        jdbc.update("INSERT INTO roles VALUES (1,'EMPLOYEE')");
        jdbc.update("INSERT INTO stores(name,active) VALUES ('Original',true)");
        provisioner = new DemoBranchProvisioner(jdbc, passwords);
    }

    @Test
    void createsExactlyThreeBranchesAndNineUsableEmployeeAccountsWithoutChangingOriginal() {
        var report = transaction.execute(status -> provisioner.provision());
        assertThat(report.branches()).hasSize(3);
        assertThat(report.branches().getFirst().name()).isEqualTo("Original");
        assertThat(report.employees()).hasSize(9);
        for (var employee : report.employees()) {
            String hash = jdbc.queryForObject("SELECT password_hash FROM users WHERE id=?", String.class, employee.userId());
            assertThat(passwords.matches(employee.password(), hash)).isTrue();
            assertThat(employee.employeeCode()).isEqualTo("NV-" + employee.userId());
            assertThat(jdbc.queryForObject("SELECT assigned_store_id FROM users WHERE id=?", Long.class, employee.userId())).isEqualTo(employee.storeId());
        }
    }

    @Test
    void rerunPreservesIdsAndPasswords() {
        var first = transaction.execute(status -> provisioner.provision());
        var hashes = jdbc.queryForList("SELECT password_hash FROM users ORDER BY id", String.class);
        var again = transaction.execute(status -> provisioner.provision());
        assertThat(again.employees()).extracting(DemoBranchProvisioner.Account::userId)
                .containsExactlyElementsOf(first.employees().stream().map(DemoBranchProvisioner.Account::userId).toList());
        assertThat(again.employees()).allMatch(account -> account.password() == null);
        assertThat(jdbc.queryForList("SELECT password_hash FROM users ORDER BY id", String.class)).isEqualTo(hashes);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM users", Long.class)).isEqualTo(9);
    }

    @Test
    void conflictingAccountRollsBackAllNewStoresAndAccounts() {
        jdbc.update("INSERT INTO users(email, enabled) VALUES ('employee.cn1.2@demo.utegear.test',false)");
        assertThatThrownBy(() -> transaction.execute(status -> provisioner.provision())).isInstanceOf(IllegalStateException.class);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM stores", Long.class)).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM users", Long.class)).isEqualTo(1);
    }

    @Test
    void unexpectedStoresAreNotModified() {
        jdbc.update("INSERT INTO stores(name,active) VALUES ('Other',true)");
        assertThatThrownBy(() -> transaction.execute(status -> provisioner.provision())).isInstanceOf(IllegalStateException.class);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM stores", Long.class)).isEqualTo(2);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM users", Long.class)).isZero();
    }
}
